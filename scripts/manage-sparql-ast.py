#!/usr/bin/env python3
"""Rebuild and verify SPARQL generated sources without modifying Java sources."""

from __future__ import annotations

import argparse
import difflib
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.error
import urllib.request
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MODULE = Path("core/queryparser/sparql")
AST = MODULE / "src/main/java/org/eclipse/rdf4j/query/parser/sparql/ast"
CONFIG = MODULE / "JavaCC"
MANIFEST = CONFIG / "generated-sources.json"
JAVACC_VERSION = "7.0.12"
JAVACC_SHA256 = "067da95992b900106afa7b775dcd32a4a044078863d6e57bb7b551f44baf5d13"
JAVACC_ARTIFACT = Path(f"net/java/dev/javacc/javacc/{JAVACC_VERSION}/javacc-{JAVACC_VERSION}.jar")
JAVACC_URL = "https://repo.maven.apache.org/maven2/" + JAVACC_ARTIFACT.as_posix()
MARKER = re.compile(rb"Generated By:.*(?:JJTree|JavaCC)")
PATCH_GROUPS = (
    ("01-optimize-SyntaxTreeBuilder..diff", {"SyntaxTreeBuilder.java"}),
    ("02-optimize-SyntaxTreeBuilderTokenManager.diff", {"SyntaxTreeBuilderTokenManager.java"}),
    ("03-preserve-ast-compatibility.diff", None),
)


class WorkflowError(RuntimeError):
    """An actionable generation, patch, formatting, or comparison failure."""


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(command: list[str], cwd: Path, log: Path) -> bytes:
    """Keep the full tool output and propagate every nonzero exit."""
    log.parent.mkdir(parents=True, exist_ok=True)
    try:
        result = subprocess.run(command, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    except OSError as error:
        raise WorkflowError(f"Cannot run {command[0]}: {error}") from error
    log.write_bytes(("$ " + " ".join(command) + "\nCWD: " + str(cwd) + "\n").encode() + result.stdout)
    if result.returncode:
        tail = result.stdout.decode("utf-8", errors="replace").splitlines()[-15:]
        raise WorkflowError(f"{command[0]} failed (exit {result.returncode}); {log}\n" + "\n".join(tail))
    return result.stdout


def names(value: object, label: str, suffix: str) -> set[str]:
    if not isinstance(value, list) or not value or not all(isinstance(name, str) for name in value):
        raise WorkflowError(f"Manifest {label} must be a nonempty list of filenames")
    if len(value) != len(set(value)):
        raise WorkflowError(f"Manifest {label} contains duplicate filenames")
    for name in value:
        if not re.fullmatch(r"[A-Za-z0-9_$.-]+", name) or name in {".", ".."} or not name.endswith(suffix):
            raise WorkflowError(f"Unsafe or invalid manifest {label} filename: {name}")
    return set(value)


def load_manifest(root: Path) -> dict:
    try:
        manifest = json.loads((root / MANIFEST).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise WorkflowError(f"Cannot read {MANIFEST}: {error}") from error
    if not isinstance(manifest, dict) or manifest.get("schema") != 1:
        raise WorkflowError("Unsupported generated-source manifest schema")
    emitted = names(manifest.get("generator_outputs"), "generator_outputs", ".java")
    patched = names(manifest.get("patched_outputs"), "patched_outputs", ".java")
    handwritten = names(manifest.get("handwritten_sources"), "handwritten_sources", ".java")
    names(manifest.get("patches"), "patches", ".diff")
    if emitted - patched or patched & handwritten:
        raise WorkflowError("Manifest must preserve every generator output and separate handwritten sources")
    if not re.fullmatch(r"[0-9a-f]{64}", str(manifest.get("grammar_sha256", ""))):
        raise WorkflowError("Manifest grammar_sha256 must be a SHA-256 digest")
    return manifest


def require_names(actual: set[str], expected: set[str], label: str) -> None:
    if actual != expected:
        missing = ", ".join(sorted(expected - actual)) or "none"
        extra = ", ".join(sorted(actual - expected)) or "none"
        raise WorkflowError(f"{label} file set differs; missing: {missing}; unexpected: {extra}")


def java_names(directory: Path) -> set[str]:
    return {path.relative_to(directory).as_posix() for path in directory.rglob("*.java")}


def verify_jar(jar: Path) -> Path:
    if not jar.is_file():
        raise WorkflowError(f"JavaCC jar is missing: {jar}; provide --jar or use --online once")
    actual = digest(jar)
    if actual != JAVACC_SHA256:
        raise WorkflowError(f"JavaCC checksum mismatch: {jar}; expected {JAVACC_SHA256}, got {actual}")
    return jar.resolve()


def obtain_jar(root: Path, supplied: Path | None, online: bool) -> Path:
    jar = supplied.resolve() if supplied else root / ".m2_repo" / JAVACC_ARTIFACT
    if jar.exists() or supplied or not online:
        return verify_jar(jar)
    jar.parent.mkdir(parents=True, exist_ok=True)
    # An incomplete download never becomes the cached artifact.
    with tempfile.NamedTemporaryFile(prefix="javacc-download-", dir=jar.parent, delete=False) as output:
        temporary = Path(output.name)
        try:
            with urllib.request.urlopen(JAVACC_URL, timeout=60) as response:
                shutil.copyfileobj(response, output)
        except (OSError, urllib.error.URLError) as error:
            raise WorkflowError(f"Cannot download {JAVACC_URL}: {error}; incomplete file: {temporary}") from error
    verify_jar(temporary)
    temporary.replace(jar)
    return jar.resolve()


def generate(root: Path, jar: Path, work: Path) -> Path:
    """Only the grammar enters a new, empty source directory."""
    build = work / "build"
    ast = build / AST
    if ast.exists():
        raise WorkflowError(f"Generation requires an empty new directory: {ast}")
    ast.mkdir(parents=True)
    shutil.copyfile(root / AST / "sparql.jjt", ast / "sparql.jjt")
    version = run(["java", "-version"], ast, work / "java-version.log").decode()
    match = re.search(r'version "(\d+)', version)
    if not match or int(match.group(1)) < 25:
        raise WorkflowError("Java 25 or newer is required for the project formatter")
    run(["java", "-cp", str(jar), "org.javacc.jjtree.Main", "sparql.jjt"], ast, work / "jjtree.log")
    run(["java", "-cp", str(jar), "org.javacc.parser.Main", "sparql.jj"], ast, work / "javacc.log")
    return build


def apply_patches(build: Path, patches: Path, manifest: dict, work: Path) -> None:
    present = {p.relative_to(patches).as_posix() for p in patches.rglob("*")
               if p.is_file() and p.suffix in {".diff", ".patch"}}
    require_names(present, set(manifest["patches"]), "Tracked patch")
    run(["git", "init", "-q"], build, work / "git-init.log")
    allowed = {(AST / name).as_posix() for name in manifest["patched_outputs"]}
    for index, name in enumerate(manifest["patches"], 1):
        patch = (patches / name).resolve()
        stats = run(["git", "-c", "core.quotePath=false", "apply", "--numstat", str(patch)],
                    build, work / f"patch-{index}-scope.log")
        targets = []
        for line in stats.decode().splitlines():
            fields = line.split("\t")
            if len(fields) != 3 or fields[0] == "-" or fields[2] not in allowed:
                raise WorkflowError(f"Patch {name} changes an unexpected or binary target: {line}")
            targets.append(fields[2])
        if not targets:
            raise WorkflowError(f"Patch {name} contains no generated-source changes")
        run(["git", "apply", "--check", str(patch)], build, work / f"patch-{index}-check.log")
        run(["git", "apply", str(patch)], build, work / f"patch-{index}-apply.log")


def prepare_build(root: Path, build: Path, work: Path) -> None:
    """Retain enough build configuration to continue a failed replay in scratch."""
    paths = run(["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--",
                 "pom.xml", "**/pom.xml", "eclipse-settings/", ".mvn/"], root, work / "build-inputs.log")
    for name in set(paths.decode().split("\0")) - {""}:
        source = root / name
        if source.is_file():
            destination = build / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, destination)
    cache = root / ".m2_repo"
    cache.mkdir(exist_ok=True)
    (build / ".m2_repo").symlink_to(cache, target_is_directory=True)


def format_sources(root: Path, build: Path, work: Path, online: bool) -> None:
    """Use the actual project formatter configuration, entirely in scratch."""
    command = ["mvn", "-B", "-ntp", "-Dmaven.repo.local=.m2_repo", "-Pformatting",
               "-Dformatter.skip=false", "-Denforcer.skip=true", "-pl", MODULE.as_posix(), "process-resources", "--fail-at-end"]
    if not online:
        command.insert(1, "-o")
    run(command, build, work / "formatter.log")


def compare_sources(root: Path, output: Path, manifest: dict, work: Path,
                    expected_directory: Path | None = None) -> None:
    patched = set(manifest["patched_outputs"])
    handwritten = set(manifest["handwritten_sources"])
    require_names(java_names(output), patched, "Replayed generated source")
    source = expected_directory if expected_directory is not None else root / AST
    expected_names = patched if expected_directory is not None else patched | handwritten
    require_names(java_names(source), expected_names, "Checked-in AST source")
    # Expected Java contents are first read here, after independent replay and formatting.
    current = {name: (source / name).read_bytes() for name in expected_names}
    marked = {name for name, data in current.items() if MARKER.search(data)}
    require_names(marked, patched, "Marked generated source partition")
    changed = []
    diffs = work / "diffs"
    for name in sorted(patched):
        actual, expected = (output / name).read_bytes(), current[name]
        if actual != expected:
            changed.append(name)
            diffs.mkdir(exist_ok=True)
            difference = "".join(difflib.unified_diff(
                actual.decode("utf-8").splitlines(keepends=True),
                expected.decode("utf-8").splitlines(keepends=True),
                fromfile=f"regenerated/{name}", tofile=f"checked-in/{name}"))
            (diffs / f"{name}.diff").write_text(difference, encoding="utf-8")
    if changed:
        raise WorkflowError("Generated source drift: " + ", ".join(changed) + f"; residual diffs: {diffs}")


def replay(root: Path, jar: Path, manifest: dict, patches: Path, work: Path, online: bool) -> Path:
    build = generate(root, jar, work)
    prepare_build(root, build, work)
    require_names(java_names(build / AST), set(manifest["generator_outputs"]), "Fresh generator output")
    apply_patches(build, patches, manifest, work)
    require_names(java_names(build / AST), set(manifest["patched_outputs"]), "Patched generated source")
    format_sources(root, build, work, online)
    require_names(java_names(build / AST), set(manifest["patched_outputs"]), "Formatted generated source")
    return build / AST


def record_patches(root: Path, jar: Path, manifest: dict, work: Path, online: bool,
                   reviewed_directory: Path | None = None) -> dict:
    """Explicit maintenance only: current source bytes become reviewed patch postimages."""
    build = generate(root, jar, work / "record")
    ast = build / AST
    emitted = java_names(ast)
    source = reviewed_directory if reviewed_directory is not None else root / AST
    handwritten = set(manifest["handwritten_sources"])
    patched = java_names(source) if reviewed_directory is not None else java_names(source) - handwritten
    if patched & handwritten:
        raise WorkflowError("Reviewed output must contain generated Java only; handwritten collision: "
                            + ", ".join(sorted(patched & handwritten)))
    if not emitted <= patched:
        raise WorkflowError("Adopt newly emitted Java sources before recording: " + ", ".join(sorted(emitted - patched)))
    candidate = dict(manifest, generator_outputs=sorted(emitted), patched_outputs=sorted(patched),
                     grammar_sha256=digest(root / AST / "sparql.jjt"))
    require_names({name for name in java_names(source) if MARKER.search((source / name).read_bytes())},
                  patched, "Marked generated source partition")
    run(["git", "init", "-q"], build, work / "record-git-init.log")
    run(["git", "add", "--force", "--", AST.as_posix()], build, work / "record-git-add.log")
    for name in sorted(patched):
        shutil.copyfile(source / name, ast / name)
    additions = sorted(patched - emitted)
    if additions:
        run(["git", "add", "-N", "--", *[(AST / name).as_posix() for name in additions]],
            build, work / "record-git-additions.log")
    candidate_patches = work / "candidate-patches"
    candidate_patches.mkdir()
    remaining = set(patched)
    patch_names = []
    for filename, selected in PATCH_GROUPS:
        files = remaining if selected is None else remaining & selected
        if not files:
            continue
        diff = run(["git", "diff", "--binary", "--no-ext-diff", "--no-color", "--no-textconv",
                    "--src-prefix=a/", "--dst-prefix=b/",
                    "--", *[(AST / name).as_posix() for name in sorted(files)]],
                   build, work / f"record-{filename}.log")
        if diff:
            (candidate_patches / filename).write_bytes(diff)
            patch_names.append(filename)
        remaining -= files
    candidate["patches"] = patch_names
    # This second rebuild uses candidate patches and no checked-in Java inputs.
    output = replay(root, jar, candidate, candidate_patches, work / "verification", online)
    compare_sources(root, output, candidate, work / "verification", reviewed_directory)
    directory = root / CONFIG / "patches"
    obsolete = {p.name for p in directory.glob("*.diff")} - set(patch_names)
    if obsolete:
        raise WorkflowError("Candidate replay succeeded, but obsolete patches need explicit removal: " + ", ".join(sorted(obsolete)))
    for name in patch_names:
        (directory / name).write_bytes((candidate_patches / name).read_bytes())
    (root / MANIFEST).write_text(json.dumps(candidate, indent=2) + "\n", encoding="utf-8")
    return candidate


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--check", action="store_true", help="verify exact bytes; default action")
    action.add_argument("--record-patches", action="store_true", help="refresh patches from reviewed Java sources")
    action.add_argument("--generate", type=Path, metavar="NEW_DIRECTORY", help="export replayed sources for review")
    parser.add_argument("--from-directory", type=Path,
                        help="with --record-patches, use reviewed generated Java instead of checked-in Java")
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root, normally detected from this script")
    parser.add_argument("--jar", type=Path, help="existing JavaCC jar; always checksum-verified")
    parser.add_argument("--online", action="store_true", help="allow pinned jar and Maven dependency downloads")
    parser.add_argument("--work-dir", type=Path, help="new/empty evidence directory; retained on success and failure")
    args = parser.parse_args(argv)
    work = None
    try:
        root = args.root.resolve()
        manifest = load_manifest(root)
        if args.from_directory and not args.record_patches:
            raise WorkflowError("--from-directory requires --record-patches")
        reviewed = args.from_directory.resolve() if args.from_directory else None
        if args.work_dir:
            work = args.work_dir.resolve()
            if work.is_relative_to(root) and not work.is_relative_to(root / "logs"):
                raise WorkflowError("Evidence directory must be outside checkout or under logs")
        else:
            work = Path(tempfile.mkdtemp(prefix="rdf4j-sparql-ast-")).resolve()
        if reviewed and work.is_relative_to(reviewed):
            raise WorkflowError("Evidence directory must not be inside reviewed source inputs")
        if args.generate:
            destination = args.generate.resolve()
            if destination.is_relative_to(root):
                raise WorkflowError("Export directory must be outside checkout")
            if destination.is_relative_to(work):
                raise WorkflowError("Export directory must be outside the evidence directory")
            if destination.exists():
                raise WorkflowError(f"Export directory must not exist: {destination}")
        if work.exists() and any(work.iterdir()):
            raise WorkflowError(f"Evidence directory must be empty: {work}")
        work.mkdir(parents=True, exist_ok=True)
        jar = obtain_jar(root, args.jar, args.online)
        if args.record_patches:
            manifest = record_patches(root, jar, manifest, work, args.online, reviewed)
            print(f"Recorded verified Git patches for {len(manifest['patched_outputs'])} generated sources")
        else:
            if not args.generate and digest(root / AST / "sparql.jjt") != manifest["grammar_sha256"]:
                raise WorkflowError("Grammar changed since patches were recorded; regenerate, review and record patches")
            output = replay(root, jar, manifest, root / CONFIG / "patches", work, args.online)
            if args.generate:
                shutil.copytree(output, destination, ignore=shutil.ignore_patterns("sparql.jjt", "sparql.jj"))
                print(f"Exported {len(manifest['patched_outputs'])} regenerated Java sources to {destination}")
            else:
                compare_sources(root, output, manifest, work)
                print(f"Verified {len(manifest['patched_outputs'])} generated sources: exact bytes and file set match")
        print(f"Evidence: {work}")
        return 0
    except (WorkflowError, OSError, UnicodeError) as error:
        print(f"SPARQL AST check failed: {error}", file=sys.stderr)
        if work:
            print(f"Evidence retained: {work}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
